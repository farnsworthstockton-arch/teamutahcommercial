#!/usr/bin/env node
// Builds one static page per listing at property/<slug>.html and refreshes the
// listing entries in sitemap.xml.
//
// Why: listing.html builds each property page in the visitor's browser from
// real-listings.json (listing.html?address=...), which search engines index
// poorly. These static copies have all of their content in the HTML itself.
//
// How: for each listing, the script runs listing.html's own page code (its
// render() function) against a small stand-in for the browser page, then
// writes what render() produced into a copy of listing.html's markup. So every
// static page shows exactly what listing.html shows for that listing (same
// facts, wording, contact block and design), and picks up any change to
// listing.html the next time the script runs.
//
// Usage, from anywhere in the repo:
//   node scripts/build-listing-pages.js           write the pages and sitemap entries
//   node scripts/build-listing-pages.js --check   change nothing; exit 1 if anything is out of date
//
// Re-run it after any change to real-listings.json or listing.html.
// Plain Node.js, no dependencies.

'use strict';

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');
const SITE = 'https://teamutahcommercial.com';
const OUT_DIR = 'property';
const MARKER = 'Generated by scripts/build-listing-pages.js';
const SITEMAP_BEGIN = '<!-- BEGIN listing pages: generated by scripts/build-listing-pages.js, do not edit by hand -->';
const SITEMAP_END = '<!-- END listing pages -->';
// Pages that only make sense while listing.html is loading data in the browser.
const DYNAMIC_ONLY_IDS = ['loading-state', 'error-state', 'not-found'];
// Other files that turn an address into a property/<slug>.html link. Their
// listingSlug() must give the same answer as the one in listing.html.
const SLUG_COPIES = ['script.js', 'map.html', 'eagle-mountain.html'];
const VOID_TAGS = new Set(['meta', 'link', 'input', 'img', 'br', 'hr', 'source']);

// Static pages: the hero photo is an <img> with alt text instead of a CSS
// background, so it needs these few extra rules on top of listing.html's.
const EXTRA_CSS = `
        /* Static listing pages (property/*.html): hero photo is an <img> with alt text. */
        .property-hero { overflow: hidden; }
        .property-hero-img { position: absolute; inset: 0; width: 100%; height: 100%; object-fit: cover; object-position: center; }
        .property-hero::before { z-index: 1; }
        .property-hero-content { z-index: 2; }
`;

// ── Small helpers ──────────────────────────────────────────────────────────

// Line endings are normalised so a Windows checkout compares equal.
function read(file) {
    return fs.readFileSync(path.join(ROOT, file), 'utf8').replace(/\r\n/g, '\n');
}

function readIfExists(file) {
    return fs.existsSync(path.join(ROOT, file)) ? read(file) : null;
}

function escapeRe(s) {
    return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function escapeHtml(s) {
    return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function escapeAttr(s) {
    return escapeHtml(s).replace(/"/g, '&quot;');
}

// JSON that is safe to place inside a <script> element.
function scriptJson(value) {
    return JSON.stringify(value).replace(/</g, '\\u003c');
}

function encodeSpaces(url) {
    return String(url).replace(/ /g, '%20');
}

function fail(message) {
    throw new Error(message);
}

// ── Reading listing.html ───────────────────────────────────────────────────

// The inline <script> that holds PROPERTY_CONTENT and render().
function findPageScript(html) {
    const re = /<script>([\s\S]*?)<\/script>/g;
    let m;
    while ((m = re.exec(html))) {
        if (m[1].includes('function render(')) return { start: m.index, end: m.index + m[0].length, code: m[1] };
    }
    return fail('listing.html: could not find the inline <script> that contains render()');
}

// Locates the element with the given id: where it starts, where its opening
// tag ends, where its closing tag starts and where it ends.
function findElement(html, id) {
    const open = new RegExp(`<([a-zA-Z][a-zA-Z0-9]*)\\b[^>]*\\sid="${escapeRe(id)}"[^>]*>`).exec(html);
    if (!open) return null;
    const tag = open[1].toLowerCase();
    const start = open.index;
    const openEnd = start + open[0].length;
    if (VOID_TAGS.has(tag)) return { tag, start, openEnd, closeStart: openEnd, end: openEnd, openTag: open[0] };
    const re = new RegExp(`<(/?)${tag}\\b[^>]*>`, 'gi');
    re.lastIndex = openEnd;
    let depth = 1;
    let m;
    while ((m = re.exec(html))) {
        depth += m[1] ? -1 : 1;
        if (depth === 0) return { tag, start, openEnd, closeStart: m.index, end: m.index + m[0].length, openTag: open[0] };
    }
    return fail(`listing.html: the element with id="${id}" is never closed`);
}

function setAttr(openTag, name, value) {
    const re = new RegExp(`(\\s${escapeRe(name)}=)"[^"]*"`);
    const attr = `"${escapeAttr(value)}"`;
    if (re.test(openTag)) return openTag.replace(re, (all, prefix) => prefix + attr);
    return openTag.replace(/\s*\/?>$/, (end) => ` ${name}=${attr}${end}`);
}

function getAttr(openTag, name) {
    const m = new RegExp(`\\s${escapeRe(name)}="([^"]*)"`).exec(openTag);
    return m ? m[1] : null;
}

// ── Running listing.html's render() ────────────────────────────────────────

// A minimal stand-in for the browser's `document`, just enough for
// listing.html's script. It records what render() writes so the build can put
// it into the HTML. Anything it does not support throws, so a change to
// listing.html that needs more shows up as a clear error instead of a quietly
// wrong page.
function fakePage(html) {
    const found = new Map();      // id -> element that exists in listing.html's markup
    const created = new Map();    // id -> element created by the script
    const headExtras = [];        // elements the script appended to <head>

    function element(id, tagName) {
        return {
            id,
            tagName,
            style: {},
            attrs: {},
            listeners: {},
            setAttribute(name, value) { this.attrs[name] = String(value); },
            addEventListener(type, fn) { (this.listeners[type] = this.listeners[type] || []).push(fn); }
        };
    }

    const document = {
        getElementById(id) {
            if (created.has(id)) return created.get(id);
            if (!found.has(id)) {
                if (!findElement(html, id)) return null;
                found.set(id, element(id, ''));
            }
            return found.get(id);
        },
        createElement(tagName) { return element('', String(tagName).toLowerCase()); },
        head: {
            appendChild(el) {
                headExtras.push(el);
                if (el.id) created.set(el.id, el);
                return el;
            }
        }
    };

    return {
        document,
        found,
        headExtras,
        reset() { found.clear(); created.clear(); headExtras.length = 0; }
    };
}

function renderListing(pageCode, html, listing) {
    const page = fakePage(html);
    const context = vm.createContext({
        document: page.document,
        window: { location: { search: '', href: '' } },
        URLSearchParams,
        console,
        setTimeout,
        fetch: () => Promise.reject(new Error('the build script does not fetch'))
    });
    // Running the script defines render() and friends. Its own start-up code
    // finds no ?address= and shows "not found"; that is thrown away by reset().
    vm.runInContext(pageCode, context, { filename: 'listing.html (inline script)' });
    const form = page.found.get('inquiryForm');
    const submitHandler = form && form.listeners.submit && form.listeners.submit[0];
    if (typeof submitHandler !== 'function') fail('listing.html: the inquiry form submit handler was not found');
    if (typeof context.listingSlug !== 'function') fail('listing.html: listingSlug() is missing');
    page.reset();

    context.__listing = JSON.parse(JSON.stringify(listing));
    vm.runInContext('render(__listing)', context, { filename: 'listing.html render()' });

    return {
        slug: context.listingSlug(listing.address),
        elements: [...page.found.values()],
        headExtras: page.headExtras.slice(),
        submitHandlerSource: submitHandler.toString()
    };
}

// ── Building one static page ───────────────────────────────────────────────

// Removes an element together with its own line(s) and the HTML comment
// directly above it (listing.html labels each block with one).
function cutElement(html, el) {
    const before = html.slice(0, el.start);
    const lead = /(?:\n[ \t]*<!--(?:(?!-->)[^\n])*-->)?\n[ \t]*$/.exec(before);
    const start = lead ? lead.index : el.start;
    return html.slice(0, start) + html.slice(el.end);
}

function removeElement(html, id) {
    const el = findElement(html, id);
    return el ? cutElement(html, el) : html;
}

// Writes one element's recorded changes into the markup.
function applyElement(html, rec) {
    const el = findElement(html, rec.id) || fail(`listing.html: no element with id="${rec.id}"`);
    const styleKeys = Object.keys(rec.style).filter(k => rec.style[k] !== undefined && rec.style[k] !== '');
    for (const key of styleKeys) {
        if (key === 'display') continue;
        if (key === 'backgroundImage' && rec.id === 'hero') continue;
        fail(`listing.html: render() sets style.${key} on #${rec.id}, which this script does not handle yet`);
    }
    if (rec.style.display === 'none') return cutElement(html, el);

    let openTag = el.openTag;
    for (const [name, value] of Object.entries(rec.attrs)) {
        openTag = setAttr(openTag, name, name === 'content' && rec.id === 'og-image' ? encodeSpaces(value) : value);
    }
    if (rec.value !== undefined) openTag = setAttr(openTag, 'value', rec.value);
    if (rec.style.display) {
        const existing = getAttr(openTag, 'style');
        openTag = setAttr(openTag, 'style', (existing ? existing.replace(/;?\s*$/, ';') : '') + 'display:' + rec.style.display);
    }

    let inner = html.slice(el.openEnd, el.closeStart);
    if (rec.textContent !== undefined) inner = escapeHtml(rec.textContent);
    if (rec.innerHTML !== undefined) inner = rec.innerHTML;
    if (rec.heroImg) inner = rec.heroImg + inner;
    return html.slice(0, el.start) + openTag + inner + html.slice(el.closeStart);
}

// Pages live one folder down, so every relative link and image in
// listing.html's markup becomes root-relative (/style.css, /photos/...).
function rootRelative(html) {
    return html.replace(/(\s(?:href|src)=)(["'])(.*?)\2/g, (all, prefix, quote, url) => {
        if (url === '' || /^(?:[a-z][a-z0-9+.-]*:|\/|#)/i.test(url)) return all;
        return prefix + quote + '/' + encodeSpaces(url) + quote;
    });
}

function headExtraHtml(el) {
    if (el.tagName !== 'script' || el.type !== 'application/ld+json') {
        fail(`listing.html: render() adds a <${el.tagName}> to <head>, which this script does not handle yet`);
    }
    const data = JSON.parse(el.textContent);
    if (typeof data.image === 'string') data.image = encodeSpaces(data.image);
    return `    <script type="application/ld+json">${scriptJson(data)}</script>\n`;
}

function buildPage(template, pageScript, listing) {
    const result = renderListing(pageScript.code, template, listing);
    const SCRIPT_SLOT = '<!--listing-page-script-->';
    let html = template.slice(0, pageScript.start) + SCRIPT_SLOT + template.slice(pageScript.end);

    const textOf = id => {
        const rec = result.elements.find(e => e.id === id);
        return rec && rec.textContent !== undefined ? String(rec.textContent).replace(/\s+/g, ' ').trim() : '';
    };
    // Sections render() hides are removed last, after anything inside them.
    const hidden = rec => rec.style.display === 'none';
    const records = [...result.elements.filter(r => !hidden(r)), ...result.elements.filter(hidden)];
    for (const rec of records) {
        if (rec.id === 'hero' && rec.style.backgroundImage) {
            const m = /^url\((['"]?)(.*)\1\)$/.exec(rec.style.backgroundImage.trim());
            if (!m) fail(`unexpected hero background for ${listing.address}: ${rec.style.backgroundImage}`);
            const alt = 'Photo of ' + (textOf('hero-address') || listing.address);
            rec.heroImg = `\n            <img class="property-hero-img" src="${escapeAttr(m[2])}" alt="${escapeAttr(alt)}" fetchpriority="high">`;
        }
        html = applyElement(html, rec);
    }
    for (const id of DYNAMIC_ONLY_IDS) html = removeElement(html, id);

    const styleEnd = html.indexOf('</style>');
    if (styleEnd === -1) fail('listing.html: no <style> block');
    const cssAt = html.lastIndexOf('\n', styleEnd);
    html = html.slice(0, cssAt) + EXTRA_CSS.trimEnd() + html.slice(cssAt);

    html = rootRelative(html);

    const headEnd = html.indexOf('</head>');
    html = html.slice(0, headEnd) + result.headExtras.map(headExtraHtml).join('') + html.slice(headEnd);

    const pageScriptHtml = [
        '<script>',
        '    // Inquiry form: the same handler as listing.html, for this listing.',
        `    let currentListingAddress = ${scriptJson(listing.address)};`,
        `    document.getElementById('inquiryForm').addEventListener('submit', ${result.submitHandlerSource});`,
        '    </script>'
    ].join('\n');
    html = html.replace(SCRIPT_SLOT, () => pageScriptHtml);

    html = html.replace(/^<!DOCTYPE html>\n/i, (doctype) => doctype +
        `<!-- ${MARKER} from real-listings.json and listing.html. Do not edit by hand:\n` +
        '     change those files, then run: node scripts/build-listing-pages.js -->\n');
    if (!html.includes(MARKER)) fail('listing.html: expected it to start with <!DOCTYPE html>');

    return { slug: result.slug, html };
}

// ── Slug checks ────────────────────────────────────────────────────────────

function checkSlugCopies(slugOf, addresses) {
    for (const file of SLUG_COPIES) {
        const src = read(file);
        const m = /function listingSlug\(address\) \{[\s\S]*?\n\s*\}/.exec(src);
        if (!m) fail(`${file}: listingSlug() not found; it must match the one in listing.html`);
        const ctx = vm.createContext({});
        vm.runInContext(m[0], ctx);
        for (const address of addresses) {
            if (ctx.listingSlug(address) !== slugOf(address)) {
                fail(`${file}: listingSlug() gives a different link than listing.html for "${address}"`);
            }
        }
    }
}

// ── Sitemap ────────────────────────────────────────────────────────────────

function sitemapEntry(listing, slug, lastmod) {
    const active = listing.section !== 'PAST PROJECTS';
    const lines = [
        '  <url>',
        `    <loc>${SITE}/${OUT_DIR}/${slug}.html</loc>`,
        `    <lastmod>${lastmod}</lastmod>`,
        `    <changefreq>${active ? 'weekly' : 'monthly'}</changefreq>`,
        `    <priority>${active ? '0.8' : '0.5'}</priority>`
    ];
    if (listing.photo) {
        const img = /^https?:\/\//.test(listing.photo) ? listing.photo : `${SITE}/${listing.photo}`;
        lines.push('    <image:image>', `      <image:loc>${escapeHtml(encodeSpaces(img))}</image:loc>`, '    </image:image>');
    }
    lines.push('  </url>');
    return lines.join('\n');
}

function previousLastmods(sitemap) {
    const map = new Map();
    const begin = sitemap.indexOf(SITEMAP_BEGIN);
    const end = sitemap.indexOf(SITEMAP_END);
    if (begin === -1 || end === -1) return map;
    const re = /<loc>([^<]+)<\/loc>\s*<lastmod>([^<]+)<\/lastmod>/g;
    const block = sitemap.slice(begin, end);
    let m;
    while ((m = re.exec(block))) map.set(m[1], m[2]);
    return map;
}

function updateSitemap(sitemap, entries) {
    const block = SITEMAP_BEGIN + '\n' + entries.join('\n\n') + '\n  ' + SITEMAP_END;
    const begin = sitemap.indexOf(SITEMAP_BEGIN);
    const end = sitemap.indexOf(SITEMAP_END);
    if (begin !== -1 && end !== -1) {
        return sitemap.slice(0, begin) + block + sitemap.slice(end + SITEMAP_END.length);
    }
    // First run: put the block right after the map.html entry, away from the
    // end of the file where new blog posts get added.
    const mapEntry = /<loc>https:\/\/teamutahcommercial\.com\/map\.html<\/loc>[\s\S]*?<\/url>\n/.exec(sitemap);
    const at = mapEntry ? mapEntry.index + mapEntry[0].length : sitemap.lastIndexOf('</urlset>');
    if (at < 0) fail('sitemap.xml: no </urlset>');
    return sitemap.slice(0, at) + '\n  ' + block + '\n' + sitemap.slice(at);
}

// ── Main ───────────────────────────────────────────────────────────────────

function main() {
    const args = process.argv.slice(2);
    if (args.includes('--help') || args.includes('-h')) {
        console.log('Usage: node scripts/build-listing-pages.js [--check]');
        return 0;
    }
    const checkOnly = args.includes('--check');
    const today = new Date().toISOString().slice(0, 10);

    const listings = JSON.parse(read('real-listings.json'));
    if (!Array.isArray(listings) || listings.length === 0) fail('real-listings.json: expected a non-empty list');
    const template = read('listing.html');
    const pageScript = findPageScript(template);

    const pages = listings.map((listing) => {
        if (!listing.address || typeof listing.address !== 'string') fail('real-listings.json: a listing has no address');
        try {
            return { listing, ...buildPage(template, pageScript, listing) };
        } catch (err) {
            err.message = `${listing.address}: ${err.message}`;
            throw err;
        }
    });

    const bySlug = new Map();
    for (const p of pages) {
        if (!p.slug) fail(`"${p.listing.address}" gives an empty page name`);
        if (bySlug.has(p.slug)) fail(`"${p.listing.address}" and "${bySlug.get(p.slug).listing.address}" would share property/${p.slug}.html`);
        bySlug.set(p.slug, p);
    }
    if (bySlug.size !== listings.length) fail(`built ${bySlug.size} pages for ${listings.length} listings`);

    const slugOf = address => pages.find(p => p.listing.address === address).slug;
    checkSlugCopies(slugOf, listings.map(l => l.address));

    // Pages to write, and the sitemap lastmod for each: a page keeps its old
    // date while its content stays the same.
    const sitemap = read('sitemap.xml');
    const lastmods = previousLastmods(sitemap);
    const changed = [];
    const entries = pages.map((p) => {
        const file = `${OUT_DIR}/${p.slug}.html`;
        const same = readIfExists(file) === p.html;
        if (!same) changed.push(file);
        const loc = `${SITE}/${file}`;
        return sitemapEntry(p.listing, p.slug, (same && lastmods.get(loc)) || today);
    });
    const newSitemap = updateSitemap(sitemap, entries);
    const sitemapChanged = newSitemap !== sitemap;

    // Generated pages for listings that are no longer in real-listings.json.
    // Only files carrying this script's marker are ever touched.
    const outDir = path.join(ROOT, OUT_DIR);
    const existing = fs.existsSync(outDir) ? fs.readdirSync(outDir).filter(f => f.endsWith('.html')) : [];
    const stale = existing.filter(f => !bySlug.has(f.replace(/\.html$/, '')) && read(`${OUT_DIR}/${f}`).includes(MARKER));
    const foreign = existing.filter(f => !bySlug.has(f.replace(/\.html$/, '')) && !stale.includes(f));

    const counts = listings.reduce((acc, l) => { acc[l.section] = (acc[l.section] || 0) + 1; return acc; }, {});
    const countText = Object.entries(counts).map(([section, n]) => `${n} ${section.toLowerCase()}`).join(', ');
    console.log(`${listings.length} listings in real-listings.json (${countText}) -> ${pages.length} pages in ${OUT_DIR}/`);
    for (const f of foreign) console.log(`  note: ${OUT_DIR}/${f} was not made by this script; left alone`);

    if (checkOnly) {
        const problems = [
            ...changed.map(f => `  out of date: ${f}`),
            ...stale.map(f => `  no longer in real-listings.json: ${OUT_DIR}/${f}`),
            ...(sitemapChanged ? ['  out of date: sitemap.xml listing entries'] : [])
        ];
        if (problems.length) {
            console.log(problems.join('\n'));
            console.log('Run: node scripts/build-listing-pages.js');
            return 1;
        }
        console.log('All listing pages and sitemap entries are up to date.');
        return 0;
    }

    fs.mkdirSync(outDir, { recursive: true });
    for (const p of pages) {
        if (changed.includes(`${OUT_DIR}/${p.slug}.html`)) fs.writeFileSync(path.join(outDir, `${p.slug}.html`), p.html);
    }
    for (const f of stale) {
        fs.unlinkSync(path.join(outDir, f));
        console.log(`  removed ${OUT_DIR}/${f} (listing no longer in real-listings.json)`);
    }
    if (sitemapChanged) fs.writeFileSync(path.join(ROOT, 'sitemap.xml'), newSitemap);
    console.log(`  ${changed.length} page(s) written, ${pages.length - changed.length} unchanged`);
    console.log(`  sitemap.xml: ${sitemapChanged ? 'listing entries updated' : 'unchanged'}`);
    return 0;
}

try {
    process.exitCode = main();
} catch (err) {
    console.error('build-listing-pages: ' + err.message);
    process.exitCode = 2;
}
